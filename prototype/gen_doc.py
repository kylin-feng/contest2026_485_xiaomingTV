def h1(t): doc.add_heading(t, level=1)
def h2(t): doc.add_heading(t, level=2)
def h3(t): doc.add_heading(t, level=3)

def p(text, bold=False, center=False, size=None, color=None, italic=False):
    para = doc.add_paragraph()
    if center:
        para.alignment = WD_ALIGN_PARAGRAPH.CENTER
    run = para.add_run(text)
    run.bold = bold
    run.italic = italic
    if size: run.font.size = Pt(size)
    if color: run.font.color.rgb = RGBColor(*color)
    return para

def bullets(items):
    for it in items:
        para = doc.add_paragraph(style='List Bullet')
        if isinstance(it, tuple):
            r = para.add_run(it[0]); r.bold = True
            para.add_run(it[1])
        else:
            para.add_run(it)

def numbered(items):
    for it in items:
        doc.add_paragraph(it, style='List Number')

def table(headers, rows, note=None):
    t = doc.add_table(rows=1 + len(rows), cols=len(headers))
    t.style = 'Table Grid'
    t.autofit = True
    for j, htxt in enumerate(headers):
        cell = t.rows[0].cells[j]
        cell.text = ''
        run = cell.paragraphs[0].add_run(htxt)
        run.bold = True
        run.font.size = Pt(10.5)
        sh = OxmlElement('w:shd'); sh.set(qn('w:val'), 'clear'); sh.set(qn('w:fill'), 'E8E4DA')
        cell._tc.get_or_add_tcPr().append(sh)
    for i, row in enumerate(rows):
        for j, ctxt in enumerate(row):
            cell = t.rows[i + 1].cells[j]
            cell.text = ''
            run = cell.paragraphs[0].add_run(str(ctxt))
            run.font.size = Pt(10.5)
    if note:
        para = doc.add_paragraph()
        run = para.add_run(note)
        run.font.size = Pt(9)
        run.font.color.rgb = RGBColor(0x66, 0x66, 0x66)
    doc.add_paragraph()
    return t

def page_break():
    doc.add_page_break()

def add_toc():
    para = doc.add_paragraph()
    run = para.add_run()
    fld = OxmlElement('w:fldChar'); fld.set(qn('w:fldCharType'), 'begin')
    instr = OxmlElement('w:instrText'); instr.set(qn('xml:space'), 'preserve')
    instr.text = 'TOC \\o "1-3" \\h \\z \\u'
    sep = OxmlElement('w:fldChar'); sep.set(qn('w:fldCharType'), 'separate')
    txt = OxmlElement('w:t'); txt.text = '（目录：在 Word 中右键此处 → 更新域，即可生成）'
    end = OxmlElement('w:fldChar'); end.set(qn('w:fldCharType'), 'end')
    run._r.append(fld); run._r.append(instr); run._r.append(sep); run._r.append(txt); run._r.append(end)

# 页脚页码
